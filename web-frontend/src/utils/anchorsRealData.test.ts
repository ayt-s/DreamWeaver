  const CHEN = "17岁少年，男性，身形偏瘦但结实，黑色短发略显凌乱，五官轮廓分明，肤色偏白，眉毛浓密，眼神透着沉稳与一丝算计，常穿粗布短衫和补丁裤子，腰间系麻绳，脚踩草鞋，举止带着穿越者的现代思维痕迹";
