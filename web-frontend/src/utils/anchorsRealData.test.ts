const urlMap = (keys: string[]) => Object.fromEntries(keys.map((k, i) => [k, `https://cdn.example.com/%d.png`.replace('%d', String(i))]));

/** 每段期望命中的场景锚（按 key 的首分句标识，避免把整段长描述写两遍） */
const EXPECTED_SCENE = [
  '小山村山坡',
  '山村茅草屋，午后',
  '山村茅草屋，午后',
  '山村茅屋废墟',
  '山村茅屋废墟',
  '村外山洞',
];

describe('锚定图命中矩阵（画布项目 40 的真实 6 段）', () => {
  const scenes = urlMap(SCENE_KEYS);
  const chars = urlMap(CHAR_KEYS);

  it('每一段命中的场景锚恰好是它自己的那个（不再退化成「全给」）', () => {
    const got = PROMPTS.map((p) => Object.keys(pickUrlsByPrompt(p, scenes).picked));
    got.forEach((keys, i) => {
      expect(keys.length).toBe(1);
      expect(keys[0].startsWith(EXPECTED_SCENE[i])).toBe(true);
    });
  });

  it('★ 第 4 段（差两字的那一镜）不得再带上「小山村山坡」或「山村茅草屋·午后」', () => {
    const keys = Object.keys(pickUrlsByPrompt(PROMPTS[3], scenes).picked);
    expect(keys.length).toBe(1);
    expect(keys[0]).toContain('山村茅屋废墟');
  });

  it('角色侧行为不变（该段提到的角色都命中，且不误命中别的角色）', () => {
    const got = PROMPTS.map((p) => Object.keys(pickUrlsByPrompt(p, chars).picked));
    expect(got[0]).toEqual(['陈浔', '大黑牛']);
    expect(got[1]).toEqual(['陈浔', '大黑牛', '小黑子']);
  });
});

